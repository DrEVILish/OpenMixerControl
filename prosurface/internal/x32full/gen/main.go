// Command gen extracts the X32 Full surface element table from OMC's
// src/x32config.cpp and writes it as Go source, so the daemon addresses
// LEDs, buttons, encoders, faders and scribble strips exactly as OMC does.
//
// Run with `go generate ./...` from the prosurface directory.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"strconv"
	"strings"
)

var (
	reLabel = regexp.MustCompile(`DefSurfaceElements\((\w+),\s*"([^"]*)"\)`)
	reDef   = regexp.MustCompile(`GetSurfaceElement\((\w+)\)\s*->Def(Button|Led|Encoder|Fader|Lcd)\(X32_BOARD_(\w+),\s*(0x[0-9A-Fa-f]+|\d+)(?:,\s*(0x[0-9A-Fa-f]+|\d+))?\)(->DefNoLed\(\))?`)
	reStrip = regexp.MustCompile(`GetSurfaceElement\(\(SurfaceElementId\)\(\(\(int\)(\w+)_1\)\+i\)\)\s*->Def(Button|Fader|Lcd)\(X32_BOARD_(\w),\s*(?:(0x[0-9A-Fa-f]+)\s*\+\s*)?i\)`)
)

type element struct {
	name, kind, board, label string
	index, backlight         int
	noLED                    bool
}

func num(s string) int {
	if s == "" {
		return 0
	}
	v, err := strconv.ParseInt(s, 0, 32)
	if err != nil {
		log.Fatalf("bad number %q: %v", s, err)
	}
	return int(v)
}

// block returns the lines between the line containing start and the first
// later line containing end.
func block(lines []string, start, end string) []string {
	for i, l := range lines {
		if strings.Contains(l, start) {
			for j := i + 1; j < len(lines); j++ {
				if strings.Contains(lines[j], end) {
					return lines[i+1 : j]
				}
			}
		}
	}
	log.Fatalf("block %q .. %q not found", start, end)
	return nil
}

func main() {
	src := flag.String("src", "../../../src/x32config.cpp", "path to OMC x32config.cpp")
	out := flag.String("out", "elements_gen.go", "output file")
	flag.Parse()

	f, err := os.Open(*src)
	if err != nil {
		log.Fatal(err)
	}
	var lines []string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		lines = append(lines, sc.Text())
	}
	f.Close()

	labels := map[string]string{}
	for _, l := range lines {
		if m := reLabel.FindStringSubmatch(l); m != nil {
			labels[m[1]] = m[2]
		}
	}

	var els []element
	for _, l := range block(lines, "if (IsModelX32Full())", "else if (IsModelX32Compact())") {
		m := reDef.FindStringSubmatch(l)
		if m == nil {
			continue
		}
		els = append(els, element{
			name: m[1], kind: m[2], board: m[3], label: labels[m[1]],
			index: num(m[4]), backlight: num(m[5]), noLED: m[6] != "",
		})
	}
	strips := 0
	for _, l := range block(lines, "if (IsModelX32FullOrCompactOrProducerOrM32OrM32R())", "IsModelAnyWing()") {
		m := reStrip.FindStringSubmatch(l)
		if m == nil {
			continue
		}
		strips++
		for i := 0; i < 8; i++ {
			name := fmt.Sprintf("%s_%d", m[1], i+1)
			els = append(els, element{
				name: name, kind: m[2], board: m[3],
				label: strings.ReplaceAll(name, "_", " "),
				index: num(m[4]) + i,
			})
		}
	}
	if len(els) < 150 || strips != 15 {
		log.Fatalf("parsed %d elements and %d strip rows; x32config.cpp layout changed?", len(els), strips)
	}

	var b bytes.Buffer
	fmt.Fprintln(&b, "// Code generated by gen/main.go from src/x32config.cpp; DO NOT EDIT.")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "package x32full")
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, `import "github.com/DrEVILish/OpenMixerControl/prosurface/internal/x32proto"`)
	fmt.Fprintln(&b)
	fmt.Fprintln(&b, "var elements = []Element{")
	for _, e := range els {
		fmt.Fprintf(&b, "\t{Name: %q, Label: %q, Kind: %s, Board: x32proto.Board%s, Index: 0x%02X",
			e.name, e.label, e.kind, boardName(e.board), e.index)
		if e.backlight != 0 {
			fmt.Fprintf(&b, ", Backlight: 0x%02X", e.backlight)
		}
		if e.noLED {
			fmt.Fprint(&b, ", NoLED: true")
		}
		fmt.Fprintln(&b, "},")
	}
	fmt.Fprintln(&b, "}")

	code, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, code, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %d elements to %s", len(els), *out)
}

func boardName(s string) string {
	switch s {
	case "MAIN":
		return "Main"
	case "EXTRA":
		return "Extra"
	}
	return s // L, M, R
}
